#!/usr/bin/env python3
"""Write the episode's line timing (English timeline, frames at 30 fps) for the scene code:
engine/app/src/episodes/<app_dir>/lines.ts with LINES = [{s, e}] (1-based line n at index n-1) and FRAMES.
Usage: pipeline/lines_ts.py <episode> [--estimate]   (--estimate: from word counts, before the voice exists)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

LAB = Path(__file__).resolve().parents[1]
FPS = 30


def main():
    ep = LAB / "episodes" / sys.argv[1]
    meta = json.loads((ep / "episode.json").read_text())
    if "--estimate" in sys.argv:
        lj = json.loads((ep / "script/lines.json").read_text())
        t, lines = 0.4, []
        for i, s in enumerate(lj["en"]):
            d = 0.36 * len(s.split()) + 0.3
            lines.append({"start": t, "end": t + d})
            t += d + lj["pause_after"].get(str(i + 1), 0.5)
        total = t + 0.6
    else:
        tm = json.loads((ep / "timing.json").read_text())
        lines, total = tm["lines"], tm["total"]
    rows = ", ".join(f"{{s: {round(x['start'] * FPS)}, e: {round(x['end'] * FPS)}}}" for x in lines)
    out = LAB / "engine/app/src/episodes" / meta["app_dir"] / "lines.ts"
    out.write_text("// Generated by pipeline/lines_ts.py from timing.json (English timeline, 30 fps). Do not edit.\n"
                   f"export const LINES = [{rows}];\nexport const FRAMES = {round(total * FPS)};\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
