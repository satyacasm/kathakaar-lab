import type {TagKind} from './kit';
import type {Fx} from './fx';
import CR from '../../../../../episodes/005-ramayana-evidence/assets/now/credits.json';

type Focus = [number, number, number];
type Cam = {lon: number; lat: number; z: number};
export type Visual =
  | {pic: string; a?: Focus; b?: Focus; credit?: string; place?: string; fx?: Fx[]; glowAt?: [number, number]; clip?: string}
  | {wipe: [string, string]; at?: number; atPh?: number; a?: Focus; b?: Focus; credit?: string; place?: string}
  | {map: {a: Cam; b?: Cam; route?: [number, number]; pins?: string[]; glow?: string[]; line?: [string, string]; grow?: boolean; tz?: number;
      tour?: [string, string, number, string?][]}}
  | {follow: string; bg: string};
export type Shot = {at: string; ph?: number; off?: number; v: Visual}; // ph: phrase of the line (clauses.ts) the shot starts on
export type Overlay = {at: string; ph?: number; till?: number; off?: number; tag?: TagKind; big?: string; sub?: string}; // ph..till: phrases it spans
export type Chapter = {n: number; shots: Shot[]; over: Overlay[]};

/** On-screen licence credit for a Commons photo (assets/now/credits.json). */
export const credit = (pic: string) => {
  const c = (CR as Record<string, {author: string; license: string}>)[pic.replace(/^now_/, '')];
  if (!c) return undefined;
  const kind = /map/.test(pic) ? 'Map' : /esa|iss/.test(pic) ? 'Image' : 'Photo';
  return c.author ? `${kind}: ${c.author}, ${c.license}, Wikimedia Commons` : 'Image: NASA, public domain';
};
type PicOpts = {a?: Focus; b?: Focus; fx?: Fx[]; glowAt?: [number, number]; clip?: string};
/** A real photo ("now"), with its place name and credit. */
const P = (pic: string, place?: string, o: PicOpts = {}): Visual => ({pic: `now_${pic}`, place, credit: credit(`now_${pic}`), ...o});
/** A painting ("then") with its motion. */
const T = (pic: string, fx: Fx[] = [], o: PicOpts = {}): Visual => ({pic: `then_${pic}`, fx, ...o});

